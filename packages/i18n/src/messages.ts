/** Состав словарей: ключи и правила множественных форм.
 *
 * Ключи словаря задаёт русский словарь — он источник истины. Остальные языки
 * типизированы тем же набором ключей, поэтому забытый перевод ловит компилятор.
 */

import { ru } from './dict/ru';

/** Формы множественного числа: в языках они различаются. */
export interface PluralForms {
  /** Форма для одного предмета. */
  one: string;
  /** Форма для нескольких (русский: 2–4). */
  few?: string;
  /** Форма для многих (русский: 5–20, 0). */
  many?: string;
  /** Общая форма для остальных чисел; в английском — основная. */
  other: string;
}

/** Текст словаря: простая строка или формы множественного числа. */
export type Message = string | PluralForms;

/** Ключ текста интерфейса. */
export type MessageKey = keyof typeof ru;

/** Словарь языка: каждый ключ русского словаря обязан быть переведён. */
export type Dictionary = Record<MessageKey, Message>;

/** Параметры подстановки в текст. */
export type MessageParams = Record<string, string | number>;

/** Русский словарь как словарь языка. */
export const RU: Dictionary = ru;
