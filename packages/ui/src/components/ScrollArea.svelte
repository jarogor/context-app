<script lang="ts">
  import type { Snippet } from 'svelte';
  import { cn } from '../utils';

  /**
   * Область прокрутки содержимого.
   *
   * Владеет вертикальной прокруткой своей области: когда содержимое выше
   * доступной высоты, нижний край достижим прокруткой, а не обрезается. Каркас
   * страницы-списка и прочие области оборачивают в него содержимое, поэтому
   * контракт прокрутки живёт в одном месте, а не повторяется в каждом корне.
   * Отступы и раскладку содержимого задаёт сам потомок — область их не меняет.
   *
   * Область объявлена контейнером (`@container`): области, вставленные в неё
   * (в том числе `PageShell`), переключают раскладку по её ширине, а не окна.
   */
  interface Props {
    /** Содержимое прокручиваемой области. */
    children: Snippet;
    /** Метка области для тестов. */
    testId?: string;
    /** Дополнительные классы области прокрутки. */
    class?: string;
  }

  let { children, testId, class: className = '' }: Props = $props();
</script>

<div
  class={cn('@container flex min-h-0 min-w-0 flex-1 flex-col overflow-y-auto', className)}
  data-testid={testId}
>
  {@render children()}
</div>
