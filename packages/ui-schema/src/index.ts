//! Словарь декларативного интерфейса плагинов.
//!
//! Плагин описывает интерфейс деревом узлов `ui-schema`, а хост рендерит его
//! компонентами и токенами единой дизайн-системы. Плагин не задаёт стили и
//! вёрстку: он указывает имя компонента и разрешённые свойства. События узлов
//! ссылаются на идентификатор действия (интент), а не на функцию, поэтому хост
//! остаётся унидирекциональным рендерером, а состояние принадлежит плагину.

/** Версия схемы декларативного интерфейса. */
export const UI_SCHEMA_VERSION = 1;

/** Узел дерева интерфейса. */
export type UiNode = UiElement | UiText;

/** Текстовый узел. */
export interface UiText {
  /** Дискриминант текстового узла. */
  type: '#text';
  /** Текст. */
  value: string;
}

/** Элемент дерева интерфейса. */
export interface UiElement {
  /** Имя компонента дизайн-системы. */
  type: string;
  /** Свойства компонента. */
  props?: Record<string, unknown>;
  /** Дочерние узлы. */
  children?: UiNode[];
  /** Обработчики событий: имя события -> идентификатор действия. */
  on?: Record<string, string>;
}

/** Проверка, что узел дерева — текстовый. */
export function isUiText(node: UiNode): node is UiText {
  return node.type === '#text';
}

/** Интент взаимодействия: событие узла, преобразованное в действие. */
export interface UiIntent {
  /** Идентификатор пространства интерфейса. */
  space: string;
  /** Идентификатор экземпляра пространства (например, секции настроек). */
  id: string;
  /** Идентификатор действия, объявленный в узле. */
  action: string;
  /** Значения контролов на момент действия. */
  values: Record<string, unknown>;
}

/** Описание компонента в каталоге разрешённых элементов. */
export interface UiComponentSpec {
  /** Имя компонента дизайн-системы. */
  name: string;
  /** Разрешённые свойства. */
  props: string[];
  /** Разрешённые события (имена, за которыми следует идентификатор действия). */
  events: string[];
  /** Может ли компонент содержать дочерние узлы. */
  children: boolean;
}

/** Описание пространства интерфейса — точки расширения со стабильным id. */
export interface UiSpaceSpec {
  /** Стабильный идентификатор пространства. */
  id: string;
  /** Человекочитаемое название пространства. */
  title: string;
  /** Разрешённые в пространстве компоненты. */
  components: string[];
}

/** Декларация плагином одного экземпляра пространства. */
export interface UiSpaceDeclaration {
  /** Стабильный идентификатор пространства. */
  space: string;
  /** Идентификатор экземпляра пространства. */
  id: string;
  /** Заголовок экземпляра (необязателен). */
  title?: string;
  /** Описание экземпляра (необязательно). */
  description?: string;
  /** Тело экземпляра деревом узлов. */
  nodes: UiNode[];
}

/** Свойства кнопки. */
export interface ButtonProps {
  /** Подпись кнопки. */
  label: string;
  /** Вариант оформления. */
  variant?: 'primary' | 'secondary' | 'ghost' | 'danger';
  /** Доступность. */
  disabled?: boolean;
}

