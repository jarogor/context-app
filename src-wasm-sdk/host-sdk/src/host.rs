//! Трейт доступа базового плагина к host-функциям приложения.
//!
//! Позволяет тестировать диспетчер операций нативно с подставным окружением, а
//! WASM-сборке — использовать host-функции ядра через [`crate::wasm::HostEnv`].

/// Host-функции, необходимые базовому плагину.
pub trait Host {
    /// Чтение служебного состояния по ключу.
    fn state_read(&self, key: &str) -> Result<Option<String>, String>;
    /// Запись служебного состояния по ключу.
    fn state_write(&self, key: &str, value: &str) -> Result<(), String>;
    /// Публикация именованного прикладного события.
    fn emit_event(&self, name: &str, payload: &str) -> Result<(), String>;
    /// Текущее время Unix в миллисекундах.
    ///
    /// Плагины, которым время не нужно, используют значение по умолчанию.
    fn now_millis(&self) -> i64 {
        0
    }
}
