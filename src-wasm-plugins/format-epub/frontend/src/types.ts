/** Типы содержимого книги, которое приходит плагину от приложения. */

/** Глава книги: заголовок и внутренний HTML с изображениями в `data:`-URI. */
export interface BookChapter {
  /** Заголовок главы, если он найден при разборе. */
  title?: string | null;
  /** Внутренний HTML главы. */
  html: string;
}

/** Содержимое книги, не зависящее от конкретного формата. */
export interface BookContent {
  /** Название книги. */
  title: string;
  /** Авторы книги. */
  authors: string[];
  /** Упорядоченные главы книги. */
  chapters: BookChapter[];
}

/** Заметка книги в непрозрачной модели приложения.
 *
 * Плагин якоря и геометрию не интерпретирует: они приходят строками и
 * возвращаются приложению такими же.
 */
export interface Note {
  /** Идентификатор заметки. */
  id: string;
  /** Тип заметки: цитата, текстовая карточка или фигура. */
  type: 'quote' | 'text' | 'shape';
  /** Непрозрачный якорь места в книге (JSON). */
  anchor: string;
  /** Выделенный текст цитаты. */
  quote: string;
  /** Идентификатор цвета заметки. */
  color: string;
  /** Номер страницы (для текучих книг не используется). */
  page?: number | null;
  /** Текст текстовой карточки. */
  text?: string;
  /** Вид фигуры. */
  shape?: string;
  /** Непрозрачная геометрия фигуры (JSON). */
  geometry?: string;
}

