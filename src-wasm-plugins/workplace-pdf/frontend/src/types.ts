/** Общие типы модуля рисования PDF.
 *
 * Описи непрозрачных данных, которыми обмениваются приложение и плагин: якоря
 * заметок, геометрия фигур, инструменты и цвета.
 */

/** Прямоугольник в долях страницы. */
export interface Rect {
  /** Левая координата в долях ширины страницы. */
  x: number;
  /** Верхняя координата в долях высоты страницы. */
  y: number;
  /** Ширина в долях ширины страницы. */
  width: number;
  /** Высота в долях высоты страницы. */
  height: number;
}

/** Тип заметки. */
export type NoteType = 'quote' | 'text' | 'shape';

/** Вид фигуры заметки. */
export type ShapeKind = 'line' | 'rectangle' | 'ellipse';

/** Тип активного инструмента создания заметок. */
export type ToolKind = 'quote' | 'text' | 'shape';

/** Активный инструмент создания заметок. */
export interface ViewerTool {
  /** Тип инструмента. */
  type: ToolKind;
  /** Вид фигуры для инструмента «фигура». */
  shape: ShapeKind;
  /** Идентификатор цвета заметки. */
  color: string;
}

/** Заметка книги в непрозрачной модели приложения. */
export interface ViewerNote {
  /** Идентификатор заметки. */
  id: string;
  /** Тип заметки; по умолчанию — цитата. */
  type?: NoteType;
  /** Непрозрачный якорь заметки (JSON). */
  anchor?: string;
  /** Текст цитаты или карточки. */
  quote?: string;
  /** Идентификатор цвета заметки. */
  color?: string;
  /** Номер страницы (справочно). */
  page?: number;
  /** Текст карточки. */
  text?: string;
  /** Вид фигуры. */
  shape?: ShapeKind;
  /** Геометрия фигуры (JSON). */
  geometry?: string;
}

/** Якорь заметки: место на странице или точка. */
export interface NoteAnchor {
  /** Версия якоря. */
  v: number;
  /** Вид привязки: прямоугольники страницы или точка. */
  kind: 'page' | 'point';
  /** Номер главы (для совместимости с EPUB). */
  chapter: number;
  /** Смещение начала (для совместимости). */
  start: number;
  /** Смещение конца (для совместимости). */
  end: number;
  /** Текст цитаты. */
  quote: string;
  /** Доля прочитанного. */
  percent: number;
  /** Номер страницы. */
  page: number;
  /** Координата точки по ширине (для `kind: "point"`). */
  x?: number;
  /** Координата точки по высоте (для `kind: "point"`). */
  y?: number;
  /** Прямоугольники выделения (для `kind: "page"`). */
  rects?: Rect[];
}

/** Геометрия фигуры: две точки в долях страницы. */
export interface ShapeGeometry {
  /** X первой точки. */
  x1: number;
  /** Y первой точки. */
  y1: number;
  /** X второй точки. */
  x2: number;
  /** Y второй точки. */
  y2: number;
}

/** Цвет в каналах 0–255. */
export interface Rgb {
  /** Красный канал. */
  r: number;
  /** Зелёный канал. */
  g: number;
  /** Синий канал. */
  b: number;
}

/** Цели перекраски страницы в тёмной теме. */
export interface PageColors {
  /** Цвет бумаги (куда уходит белый). */
  paper: Rgb;
  /** Цвет текста (куда уходит чёрный). */
  ink: Rgb;
  /** Цвет бумаги в виде CSS. */
  paperCss: string;
  /** Цвет текста в виде CSS. */
  inkCss: string;
}

/** Позиция каретки в текстовом слое. */
export interface Caret {
  /** Узел каретки. */
  node: Node;
  /** Смещение внутри узла. */
  offset: number;
  /** Текстовый слой страницы. */
  layer: Element;
}
