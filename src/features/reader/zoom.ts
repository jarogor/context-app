/** Прогрессивная шкала масштаба чтения.
 *
 * Масштаб меняется не фиксированным шагом, а по общей лестнице уровней: и
 * увеличение, и уменьшение переходят к соседнему уровню. Общая лестница делает
 * шкалу **обратимой** — увеличение и уменьшение от одного уровня возвращают к
 * тому же значению, — и **прогрессивной**: шаг растёт вместе с масштабом
 * (частые мелкие шаги у удобного для чтения размера, редкие крупные на краях
 * диапазона). Фиксированный шаг ломался на нижней границе: от минимума 5 %
 * увеличение давало 15, 25, … и сетка больше не совпадала с сеткой, полученной
 * уменьшением.
 */

/** Уровни масштаба в процентах от самого мелкого к самому крупному.
 *
 * Минимум совпадает с границей страничных форматов, максимум — с их верхней
 * границей. У текстовых книг действует свой уже диапазон, поэтому из лестницы
 * берётся только часть уровней в его границах.
 */
export const ZOOM_LEVELS: readonly number[] = [
  5, 10, 15, 20, 25, 30, 40, 50, 60, 70, 80, 90, 100, 110, 120, 130, 140, 150, 160, 170, 180, 200,
  220, 250, 300, 350, 400, 500, 600, 700, 800, 900, 1000,
];

/** Направление изменения масштаба: `1` — увеличение, `-1` — уменьшение. */
export type ZoomDirection = 1 | -1;

/** Соседний уровень масштаба в заданных границах.
 *
 * Уровни вне границ `min`…`max` отбрасываются. Если текущее значение не совпадает
 * с уровнем (например, восстановлено из прежнего состояния), берётся ближайший
 * уровень в нужную сторону: шкала остаётся обратимой и на «нестройном» значении.
 * Когда подходящего уровня нет, возвращается текущее значение.
 */
export function nextZoom(
  current: number,
  direction: ZoomDirection,
  min: number,
  max: number,
): number {
  const levels = ZOOM_LEVELS.filter((level) => level >= min && level <= max);
  if (levels.length === 0) {
    return current;
  }
  if (direction > 0) {
    return levels.find((level) => level > current) ?? levels[levels.length - 1];
  }
  const lower = levels.filter((level) => level < current);
  return lower.length > 0 ? lower[lower.length - 1] : levels[0];
}

/** Пауза затишья серии нажатий масштаба, мс.
 *
 * Должна покрывать ЧЕЛОВЕЧЕСКИЙ темп нажатий: между кликами по кнопке проходит
 * 150–350 мс (зависит от того, держат ли кнопку, жмут мышью или с тачпада).
 * Меньшая пауза истекала между кликами, и серия распадалась на отдельные шаги —
 * именно так масштаб «прорисовывал каждый промежуточный шаг». 400 мс остаются
 * незаметными для одиночного нажатия (человек не воспринимает такую задержку
 * как отклик), но надёжно покрывают серию. */
export const ZOOM_IDLE_DELAY = 400;

/** Предел ожидания затишья: дольше масштаб не откладывается, мс.
 *
 * Предел нужен только как страховка от зажатой кнопки: он не должен срабатывать
 * на обычной серии. Десять нажатий подряд занимают около 1,5 с, поэтому предел
 * заметно больше — иначе масштаб «прорисовывался» посреди серии. */
export const ZOOM_MAX_DELAY = 2500;

/** Склейка серии нажатий масштаба в одно применение.
 *
 * Кнопки масштаба общие для всех форматов (PDF, DjVu, текстовые книги), и
 * проблема у них общая: пока пользователь нажимает подряд, применяется только
 * последнее значение. Без склейки переход с 300 % на 200 % десятью нажатиями
 * пересчитывает раскладку и перерисовывает страницу на каждый шаг — это видно
 * как ступенчатое изменение масштаба.
 *
 * Ждётся ЗАТИШЬЕ, а не фиксированная пауза: таймер сбрасывается на каждом
 * нажатии, и значение применяется, когда новых нажатий нет. Фиксированная пауза
 * ломается, как только применение занимает поток: часть нажатий приходит позже
 * её истечения, и серия распадается на отдельные шаги. Верхний предел не даёт
 * зажатой кнопке откладывать масштаб бесконечно.
 *
 * Задержка отсчитывается от ПОСЛЕДНЕГО нажатия, поэтому смена направления
 * (уменьшение, сразу увеличение) склеивается так же, как движение в одну
 * сторону.
 */
export function createZoomCoalescer(apply: (value: number) => void): {
  /** Запрос применения масштаба: клик или восстановленное значение. */
  request: (value: number) => void;
  /** Немедленное применение накопленного значения (например, при закрытии). */
  flush: () => void;
} {
  let timer: ReturnType<typeof setTimeout> | null = null;
  /** Первое нажатие серии; 0 — серии нет. */
  let startedAt = 0;
  let pending: number | null = null;

  const stop = (): void => {
    if (timer !== null) {
      clearTimeout(timer);
      timer = null;
    }
  };

  const commit = (): void => {
    timer = null;
    startedAt = 0;
    const value = pending;
    pending = null;
    if (value !== null) {
      apply(value);
    }
  };

  return {
    request(value: number): void {
      const now = performance.now();
      // Серия начинается с первого запроса и живёт до применения: `startedAt`
      // обнуляется только в `commit`. Сбрасывать его по «давности» нельзя —
      // тогда отсчёт начинался бы заново на каждом клике, предел ожидания не
      // достигался бы никогда, и зажатая кнопка откладывала бы масштаб
      // бесконечно.
      if (startedAt === 0) {
        startedAt = now;
      }
      pending = value;
      stop();
      // Затишье считается от ЭТОГО клика, предел — от начала серии.
      const waited = now - startedAt;
      timer = setTimeout(commit, waited >= ZOOM_MAX_DELAY ? 0 : ZOOM_IDLE_DELAY);
    },
    flush(): void {
      stop();
      commit();
    },
  };
}
