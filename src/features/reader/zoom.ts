/** Прогрессивная шкала масштаба чтения.
 *
 * Масштаб меняется не фиксированным шагом, а по общей лестнице уровней: и
 * увеличение, и уменьшение переходят к соседнему уровню. Общая лестница делает
 * шкалу **обратимой** — увеличение и уменьшение от одного уровня возвращают к
 * тому же значению, — и **прогрессивной**: шаг растёт вместе с масштабом
 * (частые мелкие шаги у удобного для чтения размера, редкие крупные на краях
 * диапазона). Фиксированный шаг ломался на нижней границе: от минимума 5 %
 * увеличение давало 15, 25, … и сетка больше не совпадала с сеткой, полученной
 * уменьшением.
 */

/** Уровни масштаба в процентах от самого мелкого к самому крупному.
 *
 * Минимум совпадает с границей страничных форматов, максимум — с их верхней
 * границей. У текстовых книг действует свой уже диапазон, поэтому из лестницы
 * берётся только часть уровней в его границах.
 */
export const ZOOM_LEVELS: readonly number[] = [
  5, 10, 15, 20, 25, 30, 40, 50, 60, 70, 80, 90, 100, 110, 120, 130, 140, 150, 160, 170, 180, 200,
  220, 250, 300, 350, 400, 500, 600, 700, 800, 900, 1000,
];

/** Направление изменения масштаба: `1` — увеличение, `-1` — уменьшение. */
export type ZoomDirection = 1 | -1;

/** Соседний уровень масштаба в заданных границах.
 *
 * Уровни вне границ `min`…`max` отбрасываются. Если текущее значение не совпадает
 * с уровнем (например, восстановлено из прежнего состояния), берётся ближайший
 * уровень в нужную сторону: шкала остаётся обратимой и на «нестройном» значении.
 * Когда подходящего уровня нет, возвращается текущее значение.
 */
export function nextZoom(
  current: number,
  direction: ZoomDirection,
  min: number,
  max: number,
): number {
  const levels = ZOOM_LEVELS.filter((level) => level >= min && level <= max);
  if (levels.length === 0) {
    return current;
  }
  if (direction > 0) {
    return levels.find((level) => level > current) ?? levels[levels.length - 1];
  }
  const lower = levels.filter((level) => level < current);
  return lower.length > 0 ? lower[lower.length - 1] : levels[0];
}
