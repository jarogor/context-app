/** Стек слоёв, закрываемых одним действием «закрыть верхний слой».
 *
 * Слой — это то, что открылось поверх содержимого и закрывается клавишей
 * Escape: раздел настроек, панель поиска, меню заметки, правка текста,
 * переименование в списке. Слой сам сообщает о себе, пока он открыт, а не
 * перехватывает клавишу по месту: иначе каждый слой заводил бы собственный
 * обработчик Escape и порядок закрытия решался бы порядком подписки.
 *
 * Закрывается **последний открытый** слой: если поверх поиска открылось меню
 * заметки, первым уходит меню, а не поиск.
 */

/** Функция закрытия слоя. */
export type DismissLayer = () => void;

/** Открытые слои в порядке появления; закрывается последний. */
const layers: DismissLayer[] = [];

/** Регистрация открытого слоя; возвращает снятие регистрации.
 *
 * Снятие идемпотентно: повторный вызов (размонтирование после закрытия) не
 * трогает чужие слои.
 */
export function pushDismissLayer(layer: DismissLayer): () => void {
  layers.push(layer);
  return () => {
    const index = layers.lastIndexOf(layer);
    if (index >= 0) {
      layers.splice(index, 1);
    }
  };
}

/** Закрытие верхнего слоя.
 *
 * Возвращает `false`, когда закрывать нечего: действие тогда не считается
 * выполненным, и клавиша остаётся свободной.
 */
export function dismissTopLayer(): boolean {
  const layer = layers.pop();
  if (!layer) {
    return false;
  }
  layer();
  return true;
}

/** Забыть все слои (только для тестов и полной смены области). */
export function resetDismissLayers(): void {
  layers.length = 0;
}
