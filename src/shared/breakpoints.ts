/**
 * Точки перелома интерфейса для кода на JavaScript.
 *
 * Раскладка переключается утилитами Tailwind (`tablet:`, `large-tablet:`,
 * `desktop:`, `large-desktop:`), но часть поведения выбирается в скрипте (`matchMedia`):
 * телефонная компоновка меню разделов и автозакрытие боковых панелей.
 * Медиазапрос не может взять значение из CSS-переменной, поэтому точки заданы
 * здесь и совпадают с токенами `--breakpoint-*` в `packages/ui/src/tokens.css`
 * и с утилитами Tailwind. При смене значения менять оба места.
 *
 * Смена компоновки (навигация, панели, полосы управления) происходит ровно по
 * одному порогу — большому планшету (`--breakpoint-large-tablet`), поэтому
 * `NARROW_MAX_WIDTH` описывает всё, что ниже него.
 */

/** Смартфон: подступень, ниже которой прячутся подписи и лишние номера страниц. */
export const PHONE_MAX_WIDTH = '(max-width: 29.99rem)';

/** Узкое окно: телефон и маленький планшет, где панели занимают всю ширину. */
export const NARROW_MAX_WIDTH = '(max-width: 63.99rem)';
