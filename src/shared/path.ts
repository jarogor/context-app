/** Разбор последнего сегмента пути — общий на все области.
 *
 * Пути приходят и из ядра (`/lib/books/Книга.epub`), и с разделителями Windows
 * (`C:\\Books\\Книга.fb2`), поэтому сегменты выделяются по обоим разделителям.
 * Пустые сегменты (в т.ч. от оконечного разделителя) отбрасываются.
 */

/** Последний непустой сегмент пути.
 *
 * При `stripExt` у сегмента снимается расширение (часть после последней
 * точки). Если непустых сегментов нет или результат пуст, возвращается
 * исходная строка — вызывающая сторона всегда получает осмысленное значение.
 */
export function lastSegment(path: string, options: { stripExt?: boolean } = {}): string {
  const segment = path.split(/[\\/]/).filter(Boolean).pop() ?? '';
  const result = options.stripExt ? segment.replace(/\.[^.]+$/, '') : segment;
  return result || path;
}
