/** Показ окна приложения после первой отрисовки интерфейса.
 *
 * Окно создаётся скрытым (`visible: false`), чтобы белый кадр webview не успел
 * мелькнуть до отрисовки интерфейса на нужной теме. Фронтенд показывает окно
 * после первого кадра; ошибка показа не критична — окно может быть уже видимым.
 */

import { invokeCommand } from './app-bridge';

/** Показ главного окна приложения. */
export async function showAppWindow(): Promise<void> {
    try {
        await invokeCommand('show_window', {});
    } catch {
        // Окно может быть уже показано ядром; отсутствие показа не ломает интерфейс.
    }
}
