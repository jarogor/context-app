//! Открытие папки системным файловым менеджером.

/// Открытие каталога в системном файловом менеджере.
///
/// Нужна там, где пользователь хочет посмотреть содержимое папки, а не открыть
/// её как библиотеку: например, из списка библиотек — открыть её директорию.
/// Путь проверяется на существование: несуществующий каталог открывать нечем.
#[tauri::command]
pub fn open_folder(path: String) -> Result<(), String> {
    let folder = std::path::Path::new(&path);
    if !folder.is_dir() {
        return Err("папка недоступна".to_string());
    }
    open::that(folder).map_err(|_| "не удалось открыть папку".to_string())
}
